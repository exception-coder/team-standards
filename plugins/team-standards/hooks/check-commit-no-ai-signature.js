#!/usr/bin/env node
// PreToolUse(Bash|exec_command)：校验提交正文与署名，不执行传入命令。
// team-standards 明令禁止任何 AI 署名（git-commit-standards：Author 只填真实提交者）。
// 宿主/IDE 可能默认追加 Co-Authored-By；校验不依赖是否读取 Skill。
// 本 hook 在 commit 落盘前机械扫描提交信息（-m 内联 / heredoc / -F 文件），结构不完整或命中 AI 署名即阻断，
// 与改动大小、是否走 skill 无关。默认 block；TEAM_STANDARDS_COMMIT_MESSAGE_HOOK=warn 仅提示、=off 关闭。
// 局限：交互编辑、动态 Shell 和不可读取的消息文件可能无法静态提取正文，不代表已验证。

const fs = require('fs');
const path = require('node:path');
const { normalizeCommand } = require('./command-input');
const { validateCommitBody } = require('../skills/git-commit-standards/scripts/commit-message-format');
const MODE = (
  process.env.TEAM_STANDARDS_COMMIT_MESSAGE_HOOK ||
  process.env.TEAM_STANDARDS_AI_SIGNATURE_HOOK ||
  'block'
).toLowerCase();
if (MODE === 'off') process.exit(0);

function decodeQuotedArgument(value) {
  return value.replace(/\\n/g, '\n').replace(/\\r/g, '\r').replace(/\\"/g, '"');
}

function extractCommitMessage(command, cwd) {
  const paragraphs = [];
  const messagePattern = /(?:^|\s)(?:-m|--message)(?:=|\s+)(?:"((?:\\.|[^"\\])*)"|'([^']*)'|(\S+))/g;
  for (const match of command.matchAll(messagePattern)) {
    paragraphs.push(decodeQuotedArgument(match[1] || match[2] || match[3] || ''));
  }

  const filePattern = /(?:^|\s)(?:-F|--file)(?:=|\s+)(?:"([^"]+)"|'([^']+)'|(\S+))/g;
  for (const match of command.matchAll(filePattern)) {
    const filePath = match[1] || match[2] || match[3];
    if (!filePath || filePath === '-') continue;
    try { paragraphs.push(fs.readFileSync(path.resolve(cwd, filePath), 'utf8')); } catch (e) {}
  }

  return paragraphs.join('\n\n').trim();
}

function validateStructure(message) {
  if (!message) return null;

  const lines = message.split(/\r?\n/).map((line) => line.trim());
  const authorIndex = lines.findIndex((line) => /^Author:/i.test(line));
  const authorValid = authorIndex >= 0 && /^Author:\s*.+\s+<[^<>\s]+@[^<>\s]+>$/i.test(lines[authorIndex]);
  const bodyLines = lines.slice(1, authorIndex >= 0 ? authorIndex : undefined)
    .filter((line) => line && !/^\$?\(?cat\s+<</i.test(line) && line !== 'EOF' && line !== ')');

  const bodyError = validateCommitBody(bodyLines.join('\n'));
  if (bodyError) return bodyError;
  if (!authorValid) return '缺少合法 Author 行（Author: 姓名 <邮箱>）';
  return null;
}

let raw = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (c) => { raw += c; });
process.stdin.on('end', () => {
  let payload; try { payload = JSON.parse(raw); } catch (e) { process.exit(0); }
  const shell = normalizeCommand(payload);
  if (!shell) process.exit(0);
  const cmd = shell.command;
  if (!/\bgit\b[^\n]*\bcommit\b/.test(cmd)) process.exit(0);

  const message = extractCommitMessage(cmd, shell.cwd);
  const structureError = validateStructure(message);
  if (structureError) {
    process.stderr.write(
      '[team-standards] 提交信息结构不完整：' + structureError + '。\n' +
      '  规则：提交信息必须包含标题、【改动】【原因】【结果】三段中文正文和 Author: 姓名 <邮箱>。\n' +
      '  三段分别说明：代码做了什么、为什么这样做、最终解决或改善了什么。\n' +
      '  旁路：TEAM_STANDARDS_COMMIT_MESSAGE_HOOK=warn 仅提示 / =off 关闭。\n'
    );
    process.exit(MODE === 'block' ? 2 : 0);
  }

  const RULES = [
    { name: 'co-authored-by 指向 AI', re: /(^|\n)\s*co-authored-by:\s*[^\n]*\b(claude|anthropic|copilot|cursor|codex|chatgpt|openai|gemini|bard|gpt)\b/i },
    { name: 'AI 机器邮箱(noreply@anthropic.com)', re: /noreply@anthropic\.com/i },
    { name: '机器人 emoji 落款', re: /🤖/ },
    { name: 'generated with/by AI 落款', re: /(^|\n)\s*(🤖\s*)?generated\s+(with|by)\s+\[?\s*(claude|copilot|cursor|codex|chatgpt|openai|gemini)\b/i },
  ];
  const hit = RULES.find((r) => r.re.test(message));
  if (!hit) process.exit(0);

  process.stderr.write(
    '[team-standards] 提交信息含「AI 工具署名」，team-standards 明令禁止。\n' +
    '  命中：' + hit.name + '\n' +
    '  规则：git-commit-standards —— Author 只填真实提交者；禁止 Co-Authored-By 指向 AI / 机器人 emoji / Generated by … 等任何 AI 署名。\n' +
    '  处置：删除提交信息结尾的 AI 署名行后重新 commit（宿主/IDE 默认追加的签名也要一并去掉）。\n' +
    '  旁路：TEAM_STANDARDS_COMMIT_MESSAGE_HOOK=warn 仅提示 / =off 关闭。\n'
  );
  process.exit(MODE === 'block' ? 2 : 0);
});
